import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
test('community ownership, moderation, public visibility and private Storage policies',async()=>{
  const db=new PGlite();
  const alice='11111111-1111-4111-8111-111111111111',bob='22222222-2222-4222-8222-222222222222',admin='33333333-3333-4333-8333-333333333333',id='44444444-4444-4444-8444-444444444444';
  const path=`${alice}/${id}.png`;
  const as=uid=>db.exec(`reset role;set role ${uid?'authenticated':'anon'};select set_config('request.jwt.claim.sub','${uid||''}',false);`);
  try{
    await db.exec(`create role anon nologin;create role authenticated nologin;create schema auth;create table auth.users(id uuid primary key);create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;grant usage on schema auth to anon,authenticated;create schema storage;create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text);alter table storage.objects enable row level security;create function storage.foldername(text) returns text[] language sql immutable as $$select string_to_array($1,'/')$$;grant usage on schema storage to anon,authenticated;grant select,insert,delete on storage.objects to anon,authenticated;`);
    await db.exec(readFileSync('supabase/schemas/001_store.sql','utf8'));
    await db.exec(readFileSync('supabase/schemas/003_community.sql','utf8'));
    await db.exec(readFileSync('supabase/schemas/004_product_images.sql','utf8'));
    await db.exec(`insert into auth.users values('${alice}'),('${bob}'),('${admin}');insert into private.store_admins values('${admin}');`);
    assert.equal((await db.query("select public from storage.buckets where id='community'")).rows[0].public,false);
    await as(alice);
    await db.query(`insert into storage.objects(bucket_id,name) values('community','${path}')`);
    await db.query(`insert into community_shares(id,kind,display_name,caption,image_path) values('${id}','photo','Alice','My pin haul','${path}')`);
    assert.equal((await db.query('select status from community_shares')).rows[0].status,'pending');
    await assert.rejects(db.query(`insert into community_shares(kind,display_name,caption,status) values('review','Alice','Fake approval','approved')`),/row-level security/);
    await assert.rejects(db.query(`insert into community_shares(user_id,kind,display_name,caption) values('${bob}','review','Fake','Someone else')`),/row-level security/);
    assert.equal((await db.query("update community_shares set status='approved' returning id")).rows.length,0);
    await assert.rejects(db.query("update community_shares set caption='Changed'"),/permission denied/);
    await as(bob);
    assert.equal((await db.query('select * from community_shares')).rows.length,0);
    assert.equal((await db.query('select * from storage.objects')).rows.length,0);
    assert.equal((await db.query('delete from community_shares returning id')).rows.length,0);
    await assert.rejects(db.query(`insert into storage.objects(bucket_id,name) values('community','${path}')`),/row-level security/);
    await as(null);
    assert.equal((await db.query('select id from community_shares')).rows.length,0);
    assert.equal((await db.query('select * from storage.objects')).rows.length,0);
    await assert.rejects(db.query('select user_id from community_shares'),/permission denied/);
    await as(admin);
    assert.equal((await db.query('select id from community_shares')).rows.length,1);
    assert.equal((await db.query('select * from storage.objects')).rows.length,1);
    await db.query("update community_shares set status='approved'");
    await as(null);
    assert.equal((await db.query('select id from community_shares')).rows.length,1);
    assert.equal((await db.query('select * from storage.objects')).rows.length,1);
    await as(admin);await db.query("update community_shares set status='rejected'");
    await as(null);assert.equal((await db.query('select * from storage.objects')).rows.length,0);
    await as(alice);
    await assert.rejects(db.query(`insert into community_shares(kind,display_name,caption,image_path) values('photo','Alice','Bad path','${bob}/${id}.png')`),/check constraint/);
    assert.equal((await db.query('delete from storage.objects returning name')).rows.length,1);
    assert.equal((await db.query('delete from community_shares returning id')).rows.length,1);
    const productPath=`p1/${id}.png`;
    await assert.rejects(db.query(`insert into storage.objects(bucket_id,name) values('product-images','${productPath}')`),/row-level security/);
    await as(admin);
    await db.query(`insert into storage.objects(bucket_id,name) values('product-images','${productPath}')`);
    assert.equal((await db.query("select * from storage.objects where bucket_id='product-images'")).rows.length,1);
    await assert.rejects(db.query("insert into storage.objects(bucket_id,name) values('product-images','bad-path.svg')"),/row-level security/);
    await as(bob);
    assert.equal((await db.query("delete from storage.objects where bucket_id='product-images' returning name")).rows.length,0);
    await as(admin);
    assert.equal((await db.query("delete from storage.objects where bucket_id='product-images' returning name")).rows.length,1);
    await db.exec('reset role;');
    assert.equal((await db.query("select public from storage.buckets where id='product-images'")).rows[0].public,true);
  }finally{await db.close();}
});
